"""Generate real, portable local evidence and visual examples from the current code."""

import json
from dataclasses import asdict
from pathlib import Path

import cv2
import numpy as np
from _common import parser, run, write_json

from coolforge.agent import PipelineOptimizationAgent
from coolforge.benchmark import run_benchmark
from coolforge.config import PipelineConfig
from coolforge.dataset import generate_samples
from coolforge.evaluation import evaluate
from coolforge.pipeline import inspect


def main() -> None:
    args = parser("Generate actual local evidence, not benchmark fixtures")
    args.add_argument("--output", default="docs/assets")
    opt = args.parse_args()
    output = Path(opt.output)
    output.mkdir(parents=True, exist_ok=True)
    samples = generate_samples(50)
    config = PipelineConfig()
    benchmark = run_benchmark(samples, config, warmups=2, iterations=5, threads=1)
    benchmark["environment"]["cv2_file"] = "[personal installation path redacted]"
    benchmark["redactions"] = ["cv2_file: personal installation path"]
    write_json(output / "local-benchmark.json", benchmark)
    cv2.setNumThreads(1)
    result = PipelineOptimizationAgent(max_iterations=12).run(samples[:15], config)
    holdout = generate_samples(20, seed=1042)
    before = evaluate(holdout, config, repetitions=3, warmups=1)
    after = evaluate(holdout, result.final.config, repetitions=3, warmups=1)
    write_json(
        output / "local-agent.json",
        {
            "label": "LOCAL DEVELOPMENT ONLY",
            "benchmark_provenance": "local-benchmark.json",
            "tuning_seed": 42,
            "tuning_count": 15,
            "holdout_seed": 1042,
            "holdout_count": 20,
            "agent": asdict(result),
            "holdout_before": asdict(before),
            "holdout_after": asdict(after),
        },
    )
    rows = []
    for sample in samples[1:5]:
        inspected = inspect(sample.image, config)
        panes = [
            sample.image,
            cv2.cvtColor(sample.mask, cv2.COLOR_GRAY2BGR),
            cv2.cvtColor(inspected.mask, cv2.COLOR_GRAY2BGR),
            inspected.annotated_bgr,
        ]
        labelled = []
        for title, pane in zip(
            (sample.metadata["defect"], "ground truth", "prediction", "detections"),
            panes,
            strict=True,
        ):
            canvas = np.full((pane.shape[0] + 36, pane.shape[1], 3), (29, 21, 16), np.uint8)
            canvas[36:] = pane
            cv2.putText(
                canvas,
                title,
                (12, 24),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.55,
                (230, 235, 240),
                1,
                cv2.LINE_AA,
            )
            labelled.append(canvas)
        rows.append(np.hstack(labelled))
        cv2.imencode(".png", sample.image)[1].tofile(output / f"{sample.sample_id}.png")
        cv2.imencode(".png", sample.mask)[1].tofile(output / f"{sample.sample_id}_mask.png")
    cv2.imencode(".png", np.vstack(rows))[1].tofile(output / "inspection-contact-sheet.png")
    quality, timing = benchmark["evaluation"]["quality"], benchmark["evaluation"]["timing"]
    env = benchmark["environment"]
    summary = f"""# Recorded local development evidence

Generated by `python scripts/export_demo.py` from actual execution.

- Python {env["python_version"]}; OpenCV {env["cv2_version"]}; {env["machine"]}.
- OpenCV 5 verified: {env["opencv5_verified"]}; COOL verified: {env["cool_verified"]}.
- 50 images, seed 42, 384 × 256; 2 warmups and 5 measured passes per image; 1 OpenCV thread.
- Pixel F1 {quality["f1"]:.6f}; IoU {quality["iou"]:.6f};
  precision {quality["precision"]:.6f}; recall {quality["recall"]:.6f}.
- Mean {timing["mean_ms"]:.6f} ms; p50 {timing["p50_ms"]:.6f} ms;
  p95 {timing["p95_ms"]:.6f} ms; {timing["throughput_ips"]:.3f} images/s.
- Agent: {len(result.trace)} decisions, {sum(e.accepted for e in result.trace)} accepted;
  stop `{result.stop_reason}`.
- Tuning F1: {result.initial.quality["f1"]:.6f} → {result.final.quality["f1"]:.6f}.
- Held-out F1 (seed 1042, 20 images): {before.quality["f1"]:.6f} → {after.quality["f1"]:.6f}.

These are synthetic local measurements, not industrial accuracy or an AWS/COOL comparison.
Timing varies by load and hardware. The audit JSON records every rejected candidate.
Screenshots, when present, are genuine app captures from a separate interactive run;
their one-shot timing need not equal this benchmark. The module path is explicitly redacted.

Source SHA-256: `{benchmark["source_sha256"]}`.
Dataset SHA-256: `{benchmark["dataset_sha256"]}`.
Code commit at measurement: `{benchmark["git_commit"]}`.
"""
    (output / "LOCAL_RESULTS.md").write_text(summary, encoding="utf-8")
    print(
        json.dumps(
            {
                "quality": quality,
                "timing": timing,
                "accepted": sum(entry.accepted for entry in result.trace),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    run(main)
